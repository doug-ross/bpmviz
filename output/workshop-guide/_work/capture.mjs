async function shot(key, selector, caption, maxHeight = 780) {
  const loc = page.locator(selector).first();
  await loc.scrollIntoViewIfNeeded();
  await loc.evaluate(e => e.scrollIntoView({ block: 'start', inline: 'nearest' }));
  await page.waitForTimeout(120);
  const box = await loc.boundingBox();
  const x = Math.max(0, box.x), y = Math.max(0, box.y);
  const width = Math.min(box.width, 1280-x), height = Math.min(box.height, maxHeight, 1000-y);
  const file = path.join(work, 'screenshots', key+'.png');
  await page.screenshot({ path: file, clip: { x,y,width,height } });
  manifest.push({ key, file, caption, width, height }); console.log('Captured', key);
  await fs.writeFile(path.join(work, 'screenshots.json'), JSON.stringify(manifest,null,2));
}
